def format_context(chunks: list[dict]) -> str:
    """把 top-k 条款拼成带编号和出处的上下文，供 LLM 引用。

    每块的格式为：
        [资料N] 文件名（条款号） | 年份 XXXX
        <条款正文>

    块与块之间用 40 个等号分隔，方便 LLM 区分不同来源。
    """
    parts = []
    for i, c in enumerate(chunks, 1):
        # citation(c) 提取文件名+条款号，例如 "深圳市人才安居办法（第15条）"
        head = "[资料" + str(i) + "] " + citation(c) + " | 年份 " + str(c.get("year"))
        parts.append(head + NL + c["text"])
    # 两块资料之间用 40 个等号分隔，清晰区分不同来源
    sep = NL + "=" * 40 + NL
    return sep.join(parts)